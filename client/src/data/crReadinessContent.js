export function programSessionTitle(n) {
  const num = Number(n);
  const mock = MOCK_INTERVIEW_SESSIONS.find((s) => s.number === num);
  if (mock) return mock.title;
  const core = READINESS_SESSIONS.find((s) => s.number === num);
  return core?.title || `Session ${num}`;
}
