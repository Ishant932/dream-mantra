export function matchDreamzKnowledge(message, lang = 'en') {
  const text = message.toLowerCase().replace(/[^\w\s@.?]/g, ' ');
  const words = text.split(/\s+/).filter((w) => w.length > 2);
  let best = null;
  let bestScore = 0;

  for (const item of DREAMZ_KNOWLEDGE) {
    let score = 0;
    for (const key of item.keys) {
      const k = key.toLowerCase();
      if (text.includes(k)) score += k.split(' ').length * 3;
      else if (words.some((w) => w.length > 3 && (k.includes(w) || k.split(' ').some((p) => p.startsWith(w.slice(0, 4)))))) {
        score += 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = item;
    }
  }

  if (bestScore >= 1) return best[lang] || best.en;
  return null;
}
